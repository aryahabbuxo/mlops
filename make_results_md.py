"""Write RESULTS.md from results/device_models/*.csv so no number is typed by hand.

Run after train_device_models.py:  python make_results_md.py
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from solarwind.devices import pipeline as pipe
from solarwind.devices import specs as devices

OUT = Path("results/device_models")
PRETTY = {
    "naive": "Naive (training average)",
    "seasonal": "Seasonal average",
    "persistence": "Persistence (today's value)",
    "ridge": "Ridge",
    "hgb": "Gradient Boosting",
    "always_normal": "Always 'normal day'",
    "yesterday_flag": "Yesterday's flag",
    "month_rate": "Month's historical rate",
    "logistic": "Logistic regression",
    "hgb_clf": "Gradient Boosting classifier",
}
UNITS = {"sunlight_tomorrow": "kWh/m2/day", "hub_wind_tomorrow": "m/s"}


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "| " + " | ".join("---" for _ in cols) + " |"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(v) for v in r) + " |")
    return "\n".join(lines)


def reg_section(reg: pd.DataFrame, task: str, pick: str) -> str:
    t = reg[reg.task == task]
    rows = []
    for p in pipe.PLANNERS:
        v = t[(t.planner == p) & (t.split == "val")].iloc[0]
        te = t[(t.planner == p) & (t.split == "test")].iloc[0]
        rows.append(
            {
                "Planner": PRETTY[p] + (" (chosen on validation)" if p == pick else ""),
                "Validation MAE": f"{v.mae:.3f}",
                "Test MAE": f"{te.mae:.3f}",
                "Test ratio to naive": f"{te.ratio_to_naive:.3f}",
                "Test ratio to persistence": f"{te.ratio_to_persistence:.3f}",
            }
        )
    te_pick = t[(t.planner == pick) & (t.split == "test")].iloc[0]
    better = (1 - te_pick.ratio_to_persistence) * 100
    verdict = (
        f"The chosen model is {abs(better):.1f}% {'better' if better > 0 else 'worse'} than "
        f"persistence on the test period (n = {int(te_pick.n)} site-days)."
    )
    best_test = t[(t.split == "test") & t.planner.isin(["ridge", "hgb"])].sort_values("mae").iloc[0]
    note = ""
    if best_test.planner != pick:
        note = (
            f" On test, {PRETTY[best_test.planner]} scored lower, but the choice was made on "
            "validation and is not changed after seeing test."
        )
    head = f"MAE in {UNITS[task]}. Lower is better."
    return f"{head}\n\n{md_table(pd.DataFrame(rows))}\n\n{verdict}{note}\n"


def main() -> None:
    reg = pd.read_csv(OUT / "regression_results.csv")
    clf = pd.read_csv(OUT / "low_wind_results.csv")
    dev = pd.read_csv(OUT / "device_error.csv")
    picks = json.loads((OUT / "selection.json").read_text())
    d = pipe.load_nasa()
    n = d.groupby("split").size().to_dict()
    sp = devices.SPECS

    chosen = picks["low_wind_tomorrow"]
    clf_rows = []
    for rung in ["always_normal", "yesterday_flag", "month_rate", "logistic", "hgb_clf"]:
        r = clf[(clf.rung == rung) & (clf.split == "test")].iloc[0]
        clf_rows.append(
            {
                "Rung": PRETTY[rung] + (" (chosen on validation)" if rung == chosen else ""),
                "Threshold (from validation)": f"{r.threshold:.2f}",
                "Precision": f"{r.precision:.2f}",
                "Recall": f"{r.recall:.2f}",
                "F1": f"{r.f1:.2f}",
                "PR-AUC": f"{r.pr_auc:.2f}",
            }
        )
    base = clf[(clf.rung == "always_normal")].set_index("split").base_rate

    dev_rows = []
    for _, r in dev.iterrows():
        dev_rows.append(
            {
                "Planner": PRETTY[r.planner],
                "Heater MAE (C)": f"{r.heater_mae_C:.2f}",
                "Heater ratio to naive": f"{r.heater_mae_C_ratio_to_naive:.3f}",
                "Backup-day precision": f"{r.backup_precision:.2f}",
                "Backup-day recall": f"{r.backup_recall:.2f}",
                "Turbine MAE (kWh/day)": f"{r.turbine_mae_kwh_day:.2f}",
                "Turbine ratio to naive": f"{r.turbine_mae_kwh_day_ratio_to_naive:.3f}",
            }
        )

    n_backup = int(dev.backup_days_actual.iloc[0])
    text = f"""# Results: device models (weather is real, device output is generated from specs)

Generated by `make_results_md.py` from `results/device_models/`. Tracked in TensorBoard
(`tensorboard --logdir runs/tb`). Every number below is read from a file, not typed.

## Data and split

- NASA POWER daily weather, 8 Karnataka sites, {d.date.min().date()} to {d.date.max().date()}.
- Rows: train {n.get("train")}, validation {n.get("val")}, test {n.get("test")} (all sites).
- Train up to {pipe.TRAIN_END}, validation 2024, test 2025-01-01 onward. Models and cut-offs are
  fitted on train; the model is chosen on validation; test is reported once.
- Device output is generated from published specs and formulas (`specs/device_specs.csv`): Sun King
  Home 60 lamp, Giacomini GSUN 200 collector with a 100 L tank, Bergey Excel 10 turbine at
  {sp["turbine"]["hub_height_m"]:.0f} m. Weather inputs to the formulas are real.

## Task 1: sunlight tomorrow (feeds the lamp and the heater)

{reg_section(reg, "sunlight_tomorrow", picks["sunlight_tomorrow"])}
## Task 2: wind speed at hub height tomorrow (feeds the turbine)

{reg_section(reg, "hub_wind_tomorrow", picks["hub_wind_tomorrow"])}
## Task 3: low-wind day tomorrow (alert)

A day is low-wind if the hub-height wind is below the site's training-period 20th percentile.
Share of low-wind days: validation {base["val"]:.1%}, test {base["test"]:.1%}. The share changes
between periods, so thresholds are chosen on validation and precision and recall are shown instead
of accuracy. Test period:

{md_table(pd.DataFrame(clf_rows))}

## Device error on the test period

Each planner's estimate goes through the same device formulas; the error is against the output
computed from the actual weather. The lamp never runs short on real specs, so its error is 0 for
every planner and is not a useful comparison.

{md_table(pd.DataFrame(dev_rows))}

Backup days are days the heater does not reach its setpoint. There were {n_backup} in the test
period, so the flag has enough examples to judge. Precision is how many flagged days were real
backup days; recall is how many real backup days were flagged.

## What went wrong or looks odd

- The lamp with its real specs never fails, so it has no label to predict and no useful error.
- Heater backup-day recall is only about 0.5 to 0.6 for the planners that use today's weather:
  roughly 4 in 10 days that need backup are not flagged the day before.
- The low-wind share drops from validation to test, so one threshold cannot suit both periods.
- The chosen sunlight model (on validation) is not the best on test. The choice is kept.
- Heater collector values come from a certificate that lapsed on 2023-04-10; they are used as
  typical values only.

## Not done

- Device-output validation against an independent calculator (PVGIS or PVWatts).
- Real device logs (none exist for these devices in Karnataka).
- Turbine output comes from a modelled power curve, not measured turbine data.
- Hourly wind: only daily means exist, so energy uses a Rayleigh assumption.
"""
    Path("RESULTS.md").write_text(text)
    print("wrote RESULTS.md")


if __name__ == "__main__":
    main()
